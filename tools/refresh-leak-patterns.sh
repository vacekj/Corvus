#!/usr/bin/env bash
# Collects the personal identifiers the leak-check hook must never let into a commit: phone numbers
# and Signal IDs from this Mac's Corvus account data, plus your git email. Writes them to
# .git/info/leak-patterns, which is never committed. Add anything else (names, addresses, team IDs)
# to .git/info/leak-patterns.local, one per line. Also turns the hooks on for this clone.
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"
info="$(git rev-parse --git-common-dir)/info"
mkdir -p "$info"
data="${CORVUS_DATA_DIR:-$HOME/Library/Application Support/corvus}"
out="$info/leak-patterns"
{
  echo "# generated by tools/refresh-leak-patterns.sh on $(date +%F); do not commit"
  if [ -d "$data" ]; then
    find "$data/signal" -maxdepth 1 -type f \( -name 'store.db' -o -name '*.log' -o -name 'accounts.json' \) -print0 2>/dev/null |
      xargs -0 strings -n 8 2>/dev/null |
      grep -Eo '\+[1-9][0-9]{8,14}|[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}' || true
  fi
  git config user.email | grep -v 'users.noreply.github.com' || true
} | awk 'NR == 1 || !seen[$0]++' > "$out.tmp"
mv "$out.tmp" "$out"
chmod 600 "$out"
[ -f "$info/leak-patterns.local" ] || printf '# your own private strings, one per line\n' > "$info/leak-patterns.local"
git config core.hooksPath .githooks
echo "$(($(wc -l < "$out") - 1)) identifiers in $out; hooks enabled (core.hooksPath=.githooks)"
